"""Compile reviewed OSRS facts into native monster profiles and exact loot pools.
No network or database writes; generated SQL is applied only with db.py.
"""
import argparse, hashlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
DATA=Path(__file__).with_name('goblins.json')
SQL=ROOT/'sql/updates/world/3.3.5/2026_11_07_00_world.sql'
HEADER=ROOT/'src/server/game/Entities/Unit/WarscapeEnemyCatalogue.h'
SPEC=ROOT/'contrib/warscape/verifications/2026_11_07_00_world.json'
def quote(s): return "'"+s.replace("'","''")+"'"
def validate(c):
    def require(ok,message):
        if not ok:raise ValueError(message)
    require(c['source']['url'].startswith('https://oldschool.runescape.wiki/'),'Wiki provenance required')
    for field,rows in [('entry',c['items']),('entry',c['enemies']),('profile_id',c['enemies'])]:
        require(len({x[field] for x in rows})==len(rows),'Duplicate catalogue ID')
    require(len({x['name'] for x in c['items']})==len(c['items']),'Duplicate item name')
    variants={x['key']:x for x in c['variants']};loot_ids=set();names={x['name'] for x in c['items']}
    for e in c['enemies']:
        v=variants[e['variant']]
        require(v['enabled'] and len(set(v['defence_bonuses'].values()))==1,'Variant needs unsupported directional defence')
        require(len(v['stats'])==6 and all(1<=n<=1000000 for n in v['stats']),'Invalid combat stat')
        require(2<=v['attack_ticks']<=12 and 1<=v['combat_level']<=255,'Unsupported speed/level')
        require(all(-64<=n<=1000000 for n in [v['attack_bonus'],v['strength_bonus'],*v['defence_bonuses'].values()]),'Invalid combat bonus')
        require(0<e['denominator']<=1000000000 and sum(x['weight'] for x in e['outcomes'])==e['denominator'],'Loot weights do not match denominator')
        require(e['always'] in names,'Unknown guaranteed item')
        for i,o in enumerate(e['outcomes']):
            require(0<o['weight']<=e['denominator'] and 0<=o['quantity']<=255,'Invalid drop weight/quantity')
            require(o['item']=='Nothing' or (o['item'] in names and o['quantity']>0),'Unknown drop item')
            require(e['loot_base']+i not in loot_ids,'Overlapping loot IDs');loot_ids.add(e['loot_base']+i)

def compile_data(c):
    validate(c)
    items={x['name']:x for x in c['items']}
    assert len({x['entry'] for x in items.values()})==len(items)
    variants={x['key']:x for x in c['variants']}
    sql=['-- Generated by contrib/warscape/enemies/compile.py; reviewed OSRS Goblin F2P milestone.']
    for x in items.values():
        sql.append(f"INSERT INTO item_template (entry,class,subclass,name,displayid,Quality,BuyCount,stackable,AllowableClass,AllowableRace,description,Material) SELECT {x['entry']},15,0,{quote(x['name'])},displayid,1,1,200,-1,-1,'OSRS enemy catalogue collectible; gameplay use is not implemented.',Material FROM item_template WHERE entry={x['display_source']};")
    pools=[]; outcomes=[]
    for e in c['enemies']:
        v=variants[e['variant']]; assert v['enabled'] and len(set(v['defence_bonuses'].values()))==1
        assert sum(x['weight'] for x in e['outcomes'])==e['denominator']
        assert all(0<x['weight']<=128 and 0<=x['quantity']<=255 for x in e['outcomes'])
        a,st,d,r,m,h=v['stats']; p=e['profile_id']; entry=e['entry']
        sql.append(f"INSERT INTO creature_template (entry,modelid1,name,minlevel,maxlevel,faction,speed_walk,speed_run,BaseAttackTime,RangeAttackTime,unit_class,type,lootid,AIName,ExperienceModifier,RegenHealth) VALUES ({entry},{e['model']},{quote(e['name'])},{v['combat_level']},{v['combat_level']},31,1,1.14286,{v['attack_ticks']*600},2400,1,7,{e['loot_base']},'AggressorAI',0,1);")
        sql.append(f"INSERT INTO warscape_monster_profile (id,name,base_attack,base_strength,base_defence,base_ranged,base_magic,base_hitpoints,growth_attack,growth_strength,growth_defence,growth_ranged,growth_magic,growth_hitpoints,attack_bonus,strength_bonus,defence_bonus) VALUES ({p},{quote(e['name'])},{a},{st},{d},{r},{m},{h},0,0,0,0,0,0,{v['attack_bonus']},{v['strength_bonus']},{v['defence_bonuses']['dstab']});")
        sql.append(f'INSERT INTO warscape_monster_template (entry,profile_id) VALUES ({entry},{p});')
        sql.append(f"INSERT INTO warscape_monster_attack_speed (creature_entry,attack_speed_ticks) VALUES ({entry},{v['attack_ticks']});")
        first=len(outcomes)
        for i,o in enumerate(e['outcomes']):
            loot=e['loot_base']+i; outcomes.append((o['weight'],loot))
            drops=[(items[e['always']]['entry'],1)]
            if o['item']!='Nothing': drops.append((items[o['item']]['entry'],o['quantity']))
            for item,n in drops:
                sql.append(f"INSERT INTO creature_loot_template (Entry,Item,Chance,MinCount,MaxCount,Comment) VALUES ({loot},{item},100,{n},{n},'OSRS exact weighted outcome; Wiki Goblin main table 1 F2P');")
        pools.append((entry,first,len(e['outcomes']),e['denominator']))
    header='''// Generated by contrib/warscape/enemies/compile.py. Do not edit by hand.
#ifndef WARSCAPE_ENEMY_CATALOGUE_H
#define WARSCAPE_ENEMY_CATALOGUE_H
#include <array>
#include <cstdint>
namespace Warscape {
struct EnemyLootOutcome { std::uint32_t Weight, Loot; };
struct EnemyLootPool { std::uint32_t Entry, First, Count, Total; };
'''
    header+=f'inline constexpr std::array<EnemyLootOutcome,{len(outcomes)}> EnemyLootOutcomes = {{{{'+','.join('{'+f'{w},{l}'+'}' for w,l in outcomes)+'}};\n'
    header+=f'inline constexpr std::array<EnemyLootPool,{len(pools)}> EnemyLootPools = {{{{'+','.join('{'+','.join(map(str,p))+'}' for p in pools)+'}};\n'
    header+='''inline EnemyLootPool const* FindEnemyLootPool(std::uint32_t entry) {
    for (auto const& pool : EnemyLootPools) if (pool.Entry == entry) return &pool;
    return nullptr;
}
inline std::uint32_t SelectEnemyLoot(std::uint32_t entry, std::uint32_t roll) {
    for (auto const& pool : EnemyLootPools) {
        if (pool.Entry != entry || roll >= pool.Total) continue;
        for (std::uint32_t i=pool.First; i<pool.First+pool.Count; ++i) {
            auto const& outcome=EnemyLootOutcomes[i];
            if (roll < outcome.Weight) return outcome.Loot;
            roll-=outcome.Weight;
        }
    }
    return 0;
}
}
#endif
'''
    return '\n'.join(sql)+'\n',header

def legacy_release_artifacts():
    c=json.loads(DATA.read_text());sql,header=compile_data(c)
    variants={v['key']:v for v in c['variants']};items={x['name']:x for x in c['items']}
    enemy_ids=[e['entry'] for e in c['enemies']];profile_ids=[e['profile_id'] for e in c['enemies']]
    loot_ids=[e['loot_base']+i for e in c['enemies'] for i in range(len(e['outcomes']))]
    def ids(values):return ','.join(map(str,sorted(set(values))))
    conditions=[]
    for table,key,values in [('creature_template','entry',enemy_ids),('creature','id',enemy_ids),('item_template','entry',[x['entry'] for x in c['items']]),('creature_loot_template','Entry',loot_ids),('warscape_monster_profile','id',profile_ids),('warscape_monster_template','entry',enemy_ids),('warscape_monster_attack_speed','creature_entry',enemy_ids)]:
        conditions.append(f'(SELECT COUNT(*) FROM {table} WHERE {key} IN ({ids(values)}))=0')
    sources=ids(x['display_source'] for x in c['items'])
    conditions.append(f'(SELECT COUNT(*) FROM item_template WHERE entry IN ({sources}))={len(set(x["display_source"] for x in c["items"]))}')
    pre='SELECT IF('+' AND '.join(conditions)+',1,0)'
    checks=[]
    for x in c['items']:
        checks.append(f"(SELECT COUNT(*) FROM item_template WHERE entry={x['entry']} AND name={quote(x['name'])} AND class=15 AND stackable=200 AND displayid=(SELECT displayid FROM item_template WHERE entry={x['display_source']}))=1")
    for e in c['enemies']:
        v=variants[e['variant']];entry=e['entry'];p=e['profile_id']
        checks.append(f"(SELECT COUNT(*) FROM creature_template WHERE entry={entry} AND modelid1={e['model']} AND faction=31 AND lootid={e['loot_base']} AND AIName='AggressorAI' AND minlevel={v['combat_level']} AND maxlevel={v['combat_level']} AND mingold=0 AND maxgold=0)=1")
        stats=' AND '.join(f'base_{k}={n} AND growth_{k}=0' for k,n in zip(['attack','strength','defence','ranged','magic','hitpoints'],v['stats']))
        checks.append(f"(SELECT COUNT(*) FROM warscape_monster_profile WHERE id={p} AND {stats} AND attack_bonus={v['attack_bonus']} AND strength_bonus={v['strength_bonus']} AND defence_bonus={v['defence_bonuses']['dstab']})=1")
        checks.append(f'(SELECT COUNT(*) FROM warscape_monster_template WHERE entry={entry} AND profile_id={p})=1')
        checks.append(f"(SELECT COUNT(*) FROM warscape_monster_attack_speed WHERE creature_entry={entry} AND attack_speed_ticks={v['attack_ticks']})=1")
        for i,o in enumerate(e['outcomes']):
            loot=e['loot_base']+i;drops=[(items[e['always']]['entry'],1)]
            if o['item']!='Nothing':drops.append((items[o['item']]['entry'],o['quantity']))
            checks.append(f'(SELECT COUNT(*) FROM creature_loot_template WHERE Entry={loot})={len(drops)}')
            for item,n in drops:checks.append(f'(SELECT COUNT(*) FROM creature_loot_template WHERE Entry={loot} AND Item={item} AND Chance=100 AND MinCount={n} AND MaxCount={n})=1')
    spec=json.dumps({'sha1':hashlib.sha1(sql.encode()).hexdigest().upper(),'precondition_sql':pre,'verify_sql':'SELECT IF('+ ' AND '.join(checks)+',1,0)'},indent=2)+'\n'
    return {SQL: sql, SPEC: spec}


def main():
    from family_catalogue import release_artifacts, runtime_header
    from expansion_release import artifacts as expansion_artifacts
    import copy
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--write', action='store_true', help='Create new release artifacts and update generated runtime header')
    args = parser.parse_args()
    old = json.loads(DATA.read_text(encoding='utf-8'))
    artifacts = legacy_release_artifacts()
    prior = copy.deepcopy(old)
    prior['families'] = []
    combined = {'sources': {}, 'families': [], 'enemies': []}
    releases = json.loads(Path(__file__).with_name('releases.json').read_text())
    for release in releases:
        path = Path(__file__).with_name(release['data'])
        pack = json.loads(path.read_text(encoding='utf-8'))
        if release.get('creates_family_schema', False):
            artifacts.update(release_artifacts(pack, old))
        else:
            artifacts.update(expansion_artifacts(pack, prior, add_combat_columns=release.get('adds_source_combat_columns', False), add_slayer_column=release.get('adds_slayer_reference_column', False)))
        for key in ('families', 'enemies'):
            if key == 'families':
                combined[key].extend(f for f in pack[key] if f['id'] not in {old['id'] for old in combined[key]})
            else:
                combined[key].extend(pack[key])
        combined['sources'].update(pack['sources'])
        prior['families'].extend(f for f in pack['families'] if f['id'] not in {old['id'] for old in prior['families']})
        prior['enemies'].extend(pack['enemies'])
        prior['items'].extend(pack['items'])
        prior.setdefault('native_references', []).extend(pack.get('native_references', []))
    for path, text in artifacts.items():
        if path.exists():
            if path.read_text(encoding='utf-8') != text:
                raise ValueError(f'Immutable release differs: {path}; add a new release instead')
        elif args.write:
            path.write_text(text, encoding='utf-8')
        else:
            raise ValueError(f'Missing release artifact: {path}')
    header = runtime_header(combined, old)
    if args.write:
        HEADER.write_text(header, encoding='utf-8')
    elif HEADER.read_text(encoding='utf-8') != header:
        raise ValueError('Stale combined runtime header')
    print('PASS: immutable releases, family metadata and combined runtime catalogue agree')


if __name__ == '__main__':
    main()
